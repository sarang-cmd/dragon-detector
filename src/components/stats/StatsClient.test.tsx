import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import { render, screen, waitFor, cleanup } from '@testing-library/react';
import { SWRConfig } from 'swr';
import { UnitProvider } from '@/context/unit-context';
import { StatsClient } from './StatsClient';
import type {
  HistoryApiResponse,
  HistoryPoint,
  WeatherApiResponse,
  WeatherReading,
} from '@/lib/types';
import projectStats from '@/lib/project-stats.json';

/** 24 hourly readings: two Berlin calendar days, rain every sixth hour. */
function hourlyPoints(count = 24): HistoryPoint[] {
  const start = Date.parse('2026-11-08T00:00:00.000Z');
  const out: HistoryPoint[] = [];
  for (let i = 0; i < count; i++) {
    const temp = 2 + Math.sin(i / 4) * 4;
    out.push({
      timestamp: new Date(start + i * 3_600_000).toISOString(),
      temperatureC: Math.round(temp * 10) / 10,
      humidityPct: 70 + (i % 10),
      windSpeedKmh: 5 + (i % 7),
      windGustKmh: 10 + (i % 11),
      windDirectionDeg: (i * 45) % 360,
      rainRateMmH: i % 6 === 0 ? 1.2 : 0,
      pressureHpa: 1008 + (i % 5),
      uvIndex: i % 5,
      solarWm2: (i % 6) * 100,
      dewPointC: Math.round((temp - 2) * 10) / 10,
      feelsLikeC: Math.round((temp - 1) * 10) / 10,
    });
  }
  return out;
}

const reading: WeatherReading = {
  timestamp: '2026-11-08T23:00:00.000Z',
  source: 'mock',
  temperatureC: 3.2,
  humidityPct: 84,
  pressureHpa: 1011.2,
  windSpeedKmh: 8,
  windGustKmh: 12,
  windDirectionDeg: 180,
  rainRateMmH: 0,
  rainTodayMm: 1.2,
};

function weatherPayload(): WeatherApiResponse {
  return {
    reading,
    history: { h24: hourlyPoints(24), d7: hourlyPoints(24) },
    meta: {
      fetchedAt: new Date().toISOString(),
      fetchedAtServer: new Date().toISOString(),
      stale: false,
      offline: false,
      measuredAt: new Date().toISOString(),
      source: 'mock',
    },
  };
}

function historyPayload(points: HistoryPoint[]): HistoryApiResponse {
  return {
    points,
    range: '7d',
    fetchedAt: new Date().toISOString(),
    measuredAt: new Date().toISOString(),
  };
}

let historyPoints: HistoryPoint[];

// jsdom has no ResizeObserver, which recharts' ResponsiveContainer needs.
class ResizeObserverStub {
  observe() {}
  unobserve() {}
  disconnect() {}
}

function ok(body: unknown): Response {
  return { ok: true, status: 200, json: async () => body } as unknown as Response;
}

beforeEach(() => {
  vi.stubGlobal('ResizeObserver', ResizeObserverStub);
  historyPoints = hourlyPoints();
  vi.stubGlobal(
    'fetch',
    vi.fn(async (input: unknown) => {
      const url = String(input);
      if (url.includes('/api/history')) return ok(historyPayload(historyPoints));
      if (url.includes('/api/weather')) return ok(weatherPayload());
      throw new Error(`unexpected fetch: ${url}`);
    })
  );
});

afterEach(() => {
  cleanup();
  vi.unstubAllGlobals();
  vi.restoreAllMocks();
});

function renderStats() {
  return render(
    <UnitProvider>
      <SWRConfig value={{ provider: () => new Map(), dedupingInterval: 0 }}>
        <StatsClient />
      </SWRConfig>
    </UnitProvider>
  );
}

describe('StatsClient', () => {
  it('renders the records section with values from the window', async () => {
    renderStats();

    await waitFor(() => {
      expect(screen.getByRole('heading', { name: 'Records' })).toBeTruthy();
    });
    // Highest and lowest temperature rows come from the same series.
    expect(screen.getByText('Highest temperature')).toBeTruthy();
    expect(screen.getByText('Lowest temperature')).toBeTruthy();
    // Sensors that reported nothing are left out rather than shown as zero.
    expect(screen.queryByText('Peak UV index')).not.toBeNull();
  });

  it('shows one row per Berlin calendar day', async () => {
    renderStats();

    await waitFor(() => {
      expect(screen.getAllByRole('rowheader', { name: '2026-11-08' })).toHaveLength(1);
    });
    expect(screen.getAllByRole('rowheader', { name: '2026-11-09' })).toHaveLength(1);
    // The series ends at 00:00 Berlin on the 9th, so no third day appears.
    expect(screen.queryAllByRole('rowheader', { name: '2026-11-10' })).toHaveLength(0);
  });

  it('reports complete coverage for a gap-free series', async () => {
    renderStats();

    await waitFor(() => {
      expect(screen.getByText('Record coverage')).toBeTruthy();
    });
    expect(screen.getByText('100 %')).toBeTruthy();
    expect(screen.getByText(`${historyPoints.length}`)).toBeTruthy();
  });

  it('always shows the build statistics, even before data arrives', async () => {
    historyPoints = [];
    renderStats();

    await waitFor(() => {
      expect(screen.getByRole('heading', { name: 'This build' })).toBeTruthy();
    });
    // The JSON is generated by `pnpm stats`, so assert it is rendered, not
    // the specific counts (they change with every commit).
    expect(screen.getByText('Application code')).toBeTruthy();
    expect(
      screen.getByText(projectStats.code.lines.toLocaleString('en-GB'))
    ).toBeTruthy();
  });

  it('says so when the archive is empty instead of showing zeroes', async () => {
    historyPoints = [];
    renderStats();

    await waitFor(() => {
      expect(screen.getByText(/No readings in this window yet/)).toBeTruthy();
    });
    expect(screen.queryByRole('heading', { name: 'Records' })).toBeNull();
  });
});

describe('StatsClient wind card', () => {
  // Scoped to tiles: "Strongest gust" is also a row header in the records
  // table further down the page.
  function tileFor(label: string): HTMLElement {
    const tile = Array.from(document.querySelectorAll('.stat-tile')).find(
      (t) => t.querySelector('dt')?.textContent === label,
    );
    if (!tile) throw new Error(`no tile for ${label}`);
    return tile as HTMLElement;
  }

  it('lays the four tiles out two across, not four', async () => {
    renderStats();
    await waitFor(() => {
      expect(screen.getByText('Prevailing')).toBeTruthy();
    });

    const grid = tileFor('Prevailing').parentElement;
    expect(grid?.tagName).toBe('DL');
    // Four across inside the wind column left each tile ~90px wide, which
    // clipped the labels and split values from their units.
    expect(grid?.className).toContain('grid-cols-2');
    expect(grid?.className).not.toContain('lg:grid-cols-4');
    expect(grid?.querySelectorAll('.stat-tile')).toHaveLength(4);
  });

  it('shows the prevailing direction as a short abbreviation', async () => {
    renderStats();
    await waitFor(() => {
      expect(screen.getByText('Prevailing')).toBeTruthy();
    });

    const tile = tileFor('Prevailing');
    const value = tile.querySelector('.stat-value')?.textContent?.trim() ?? '';
    // "East-northeast" in a large monospace face was the worst case: it broke
    // mid-word. The abbreviation is three characters at most.
    expect(value).toMatch(/^[NSEW]{1,3}$/);
    // The long name is still there, just demoted to the secondary line.
    expect(tile.querySelector('.stat-sub')?.textContent ?? '').toMatch(/(North|East|South|West)/);
  });

  it('welds each value to its unit so they cannot split across lines', async () => {
    renderStats();
    await waitFor(() => {
      expect(screen.getByText('Mean speed')).toBeTruthy();
    });

    for (const label of ['Mean speed', 'Strongest gust', 'Calm readings']) {
      const tile = tileFor(label);
      const dd = tile.querySelector('.stat-value');
      const unit = tile.querySelector('.stat-unit');
      expect(unit).not.toBeNull();
      // A non-breaking space is the only thing separating number and unit,
      // so a narrow tile can no longer park the unit on its own line.
      expect(dd?.textContent ?? '').toContain('\u00a0');
      expect(unit?.textContent?.trim()).toBeTruthy();
    }
  });
});
